import { COLORS } from './Palette'

export type PixelTemplate = {
  id: string
  name: string
  size: 32
  pixels: (string | null)[][]
}

function colorOf(name: (typeof COLORS)[number]['name']) {
  const found = COLORS.find((item) => item.name === name)
  if (!found) throw new Error(name)
  return found.hex
}

const INK: Record<string, string> = {
  R: colorOf('红'),
  O: colorOf('橙'),
  Y: colorOf('黄'),
  G: colorOf('绿'),
  C: colorOf('青'),
  B: colorOf('蓝'),
  V: colorOf('紫'),
  P: colorOf('粉'),
  N: colorOf('棕'),
  K: colorOf('黑'),
  W: colorOf('白'),
  A: colorOf('灰'),
  E: colorOf('深绿'),
  L: colorOf('浅蓝'),
  M: colorOf('米色'),
  H: colorOf('深红'),
}

const TEMPLATE_SIZE = 32

function picture(rows: readonly string[]): (string | null)[][] {
  if (rows.length !== TEMPLATE_SIZE) throw new Error(`模板高度应为 ${TEMPLATE_SIZE}，实际 ${rows.length}`)
  return rows.map((row, y) => {
    const cells = [...row]
    if (cells.length !== TEMPLATE_SIZE) throw new Error(`模板第 ${y + 1} 行宽度应为 ${TEMPLATE_SIZE}，实际 ${cells.length}`)
    return cells.map((cell) => {
      if (cell === '.') return null
      const hex = INK[cell]
      if (!hex) throw new Error(`模板有调色板以外的色块 ${cell}`)
      return hex
    })
  })
}

