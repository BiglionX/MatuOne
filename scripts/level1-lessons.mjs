const COLOR = { red: '红色', blue: '蓝色', green: '绿色', orange: '橙色', purple: '紫色' }

function argCall(name, label, func, def, alt, hint, extra = {}) {
  const type = extra.type ?? 'number'
  const param = {
    name,
    label,
    type,
    default: type === 'select' ? String(def) : def,
    apply: { kind: 'arg', func, argIndex: 0, occurrence: extra.occurrence ?? 1 },
    hint,
  }
  if (type === 'number') {
    param.min = extra.min
    param.max = extra.max
    param.step = extra.step
  } else {
    param.options = extra.options
  }
  return { param, alt }
}

function assignNum(name, label, def, alt, min, max, step, hint) {
  return {
    param: {
      name,
      label,
      type: 'number',
      min,
      max,
      step,
      default: def,
      apply: { kind: 'assign', variable: name },
      hint,
    },
    alt,
  }
}

function assignColor(name, from, to, label) {
  return {
    param: {
      name,
      label,
      type: 'select',
      default: from,
      options: [
        { value: from, label: COLOR[from] },
        { value: to, label: COLOR[to] },
      ],
      apply: { kind: 'assign', variable: name },
      hint: `换成${COLOR[to]}，颜色会跟着变。`,
    },
    alt: to,
  }
}

